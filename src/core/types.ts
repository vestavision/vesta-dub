/**
 * Core type definitions for Vesta Dub (P1, P2-A, P2-B & P2.6)
 */

export type TTSProviderId = 'antalia' | 'ema-lightning' | 'piper-fahrettin';

export interface SynthesisOptions {
  signal?: AbortSignal;
  speed?: number;
  pitch?: number;
  [key: string]: any;
}

export interface SubtitleCue {
  id: string;
  index: number;
  startTime: number; // in seconds
  endTime: number;   // in seconds
  duration: number;  // in seconds
  originalText: string;
  turkishText: string;
  /** Pronunciation-optimized text exclusively for Turkish TTS */
  spokenText?: string;
  /** TTS-only token offsets refer to unchanged Turkish display text, not source-time words. */
  speechPreparation?: import('../tts/FillerPreparation').SpeechPreparation;
  speakerId?: string; // 'speaker-a' | 'speaker-b'
  acquisition?: { requestId?: string; source: 'preloaded_track' | 'live_dom' | 'local_asr'; wallMs: number; monotonicMs: number; videoSec: number; language: string | null; timestamps: 'supplied' | 'estimated' };
  isAutoGenerated?: boolean;
  mergedFromCount?: number;
  /** Sentence assembly metadata. Present for preloaded cues rebuilt from fragments. */
  assembly?: CueAssembly;
  // Adaptive timing metadata
  syncMetadata?: CueSyncMetadata;
}

export interface CueAssembly {
  sourceCueIds: string[];
  confidence: number;
  boundary: 'punctuation' | 'gap' | 'duration' | 'speaker' | 'end';
  dedupedTokens: number;
  tokenCount: number;
  semanticCompromises?: string[];
  contextAligned?: boolean;
}

export type SyncStrategy =
  | 'normal'
  | 'gap_absorbed'
  | 'time_stretched'
  | 'concise_resynthesized'
  | 'unresolved_overflow_compromise'
  | 'graceful_fade';

export interface CueSyncMetadata {
  originalDuration: number;
  audioDuration: number;
  availableWindow: number;
  requiredSpeed: number;
  actualSpeed: number;
  startDriftMs: number;
  overflowSec: number;
  strategyUsed: SyncStrategy;
  conciseTextUsed?: string;
  isCompromised?: boolean;
  compromiseSec?: number;
  pitchDeviationCents?: number;
}

export interface SubtitleTrack {
  id: string;
  languageCode: string;
  name: string;
  kind?: 'asr' | 'standard';
  isDefault?: boolean;
  baseUrl?: string;
  vssId?: string;
}

export interface ExtensionMessage {
  type:
    | 'GET_STATE'
    | 'TOGGLE_DUBBING'
    | 'SET_ACTIVATION_MODE'
    | 'SET_ORIGINAL_VOLUME'
    | 'SET_DUBBING_VOLUME'
    | 'SET_DUCKING_VOLUME'
    | 'SET_TRACK'
    | 'SELECT_TRACK'
    | 'UPDATE_SPEAKER'
    | 'SET_CUE_SPEAKER'
    | 'PURGE_MODELS'
    | 'RECOVERY_AUDIO_DIAGNOSTIC'
    | 'GET_RECOVERY_TRACE'
    | 'RECOVERY_STATE_SNAPSHOT'
    | 'TRIGGER_DIAGNOSTIC_REPLAY'
    | 'GET_DIAGNOSTIC_SNAPSHOT'
    | 'START_DOGFOOD_RECORDING'
    | 'STOP_DOGFOOD_RECORDING'
    | 'GET_TELEMETRY_LOGS'
    | 'CLEAR_TELEMETRY_LOGS'
    | 'SET_ADAPTIVE_SYNC'
    | 'SET_SPEECH_RESEGMENTATION'
    | 'STATE_UPDATE'
    | 'TRANSLATE_TEXT'
    | 'TEST_SYNTHESIS'
    | 'DOGFOOD_START_SESSION'
    | 'DOGFOOD_STOP_SESSION'
    | 'DOGFOOD_GET_STATS'
    | 'DOGFOOD_EXPORT_REPORT'
    | 'DOGFOOD_CLEAR_DATA'
    | 'GET_PAUSE_ISOLATION'
    | 'SET_PAUSE_ISOLATION';
  [key: string]: any;
}

export type RuntimeStatus =
  | 'idle'
  | 'loading_captions'
  | 'translating'
  | 'loading_model'
  | 'buffering'
  | 'playing'
  | 'waiting_for_live_caption'
  | 'error';

export interface ExtensionState {
  activation?: import('../activation/ActivationPolicy').ActivationSnapshot;
  videoDetected: boolean;
  playback: VideoPlaybackState | null;
  tracks: SubtitleTrack[];
  selectedTrack: SubtitleTrack | null;
  cues: SubtitleCue[];
  settings: ExtensionSettings;
  metrics: DubbingMetrics;
  status: RuntimeStatus;
  errorMessage: string | null;
  modelStatus: Record<string, ModelStatus>;
  captionMode?: 'preloaded' | 'live';
  captionSource?: any;
}

export interface ModelStatus {
  cached: boolean;
  downloading: boolean;
  progress: number;
  sizeBytes: number;
}

export interface VideoPlaybackState {
  currentTime: number;
  duration: number;
  paused: boolean;
  playbackRate: number;
  volume: number;
  muted: boolean;
  videoId: string;
  title: string;
}

export interface SpeakerSlot {
  id: string;
  name: string;
  providerId: TTSProviderId;
  speed: number;
  voiceId?: string;
  pitch?: number;
}

export interface ExtensionSettings {
  activationMode?: import('../activation/ActivationPolicy').ActivationMode;
  enabled: boolean;
  originalVideoVolume: number;
  dubbingVolume: number;
  selectedTrackId: string | null;
  speakers: Record<string, SpeakerSlot>;
  defaultSpeakerId: string;
  autoTranslateCaptions: boolean;
  lookaheadWindowSec: number;
  adaptiveSyncEnabled: boolean;
  maxSpeedStretch: number;
  speechResegmentationEnabled: boolean;
}

export interface DubbingMetrics {
  activeCueIndex: number;
  currentCueText: string;
  currentSpeakerId: string;
  activeProviderId: string;
  synthesisLatencyMs: number | null;
  syncDriftMs: number | null;
  isOverflowing: boolean;
  realtimeFactor: number | null;
  bufferedCuesCount: number;
  totalCuesCount: number;
  p95StartDriftMs?: number | null;
  p95OverflowMs?: number | null;
  underrunCount?: number;
  activeStrategy?: SyncStrategy;
  scheduledSpeed?: number;
  isCompromised?: boolean;
  compromiseSec?: number;
  pitchDeviationCents?: number;
}

export interface SynthesisResult {
  audio: Float32Array;
  sampleRate: number;
  duration: number;
  timings?: Record<string, number>;
}
